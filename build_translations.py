THAI_RANGE = re.compile(r"[฀-๿]")

def _is_already_thai(text: str) -> bool:
    """Heuristic: text is already Thai if at least 25% of letters are in the
    Thai Unicode block."""
    letters = [c for c in text if c.isalpha()]
    if not letters:
        return False
    thai_count = sum(1 for c in letters if THAI_RANGE.match(c))
    return thai_count / len(letters) > 0.25


def _build_skeleton():
    """Parse the chat and write translations.skeleton.json."""
    from parser import parse_file, detect_date_format
    chat_path = "WhatsApp Chat - Payandorn Suksang (1)/_chat.txt"
    fmt = detect_date_format(chat_path)
    msgs = parse_file(chat_path, date_format=fmt)
    skel = []
    for i, m in enumerate(msgs):
        skel.append({
            "id": i,
            "timestamp": m.timestamp.isoformat(),
            "sender": m.sender,
            "is_system": m.is_system,
            "media_filename": m.media_filename,
            "original": m.text,
            "thai": "",
        })
    json.dump(skel, open("translations.skeleton.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    return skel


# IDs that existed in the very first parse pass but were dropped after we
# filtered out empty "Sender:" placeholder lines. TRANSLATIONS keys are
# expressed in that original numbering; this offset table maps the current
# (post-filter) id back to the old id used as the dict key.
_REMOVED_OLD_IDS = sorted({55, 148, 154, 247, 251, 272})

def _old_id_for(new_id: int) -> int:
    old = new_id
    for r in _REMOVED_OLD_IDS:
        if old >= r:
            old += 1
    return old


def main():
    skel = _build_skeleton()

    untranslated = []
    for entry in skel:
        text = (entry["original"] or "").strip()
        if not text:
            entry["thai"] = ""
            continue

        old = _old_id_for(entry["id"])
        if old in TRANSLATIONS:
            entry["thai"] = TRANSLATIONS[old]
        elif _is_already_thai(text):
            entry["thai"] = entry["original"]
        else:
            entry["thai"] = ""
            untranslated.append((entry["id"], text[:60]))

    json.dump(skel, open("translations.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)

    print(f"Wrote translations.json with {len(skel)} entries")
    if untranslated:
        print(f"  {len(untranslated)} untranslated:")
        for i, t in untranslated:
            print(f"    id={i}: {t}")


if __name__ == "__main__":
    main()
